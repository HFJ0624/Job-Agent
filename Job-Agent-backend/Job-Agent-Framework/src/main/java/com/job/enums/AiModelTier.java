package com.job.enums;

/**
 * 功能:模型档位（企业级对标 G1：模型分级路由）。
 *
 * 说明:
 * 1. 同一业务场景（sceneCode）下，可按任务难度路由到不同档位模型：
 *    分类/抽取/压缩走 LIGHT 控成本，总结/生成等质量敏感任务走 PRO。
 * 2. 路由未配置对应档位时，网关降级使用场景默认路由，保证老配置可用。
 */
public enum AiModelTier {

    /**
     * 轻量档：意图分类、参数抽取、摘要压缩等低成本任务。
     */
    LIGHT,

    /**
     * 标准档：默认档位，平衡成本与质量。
     */
    STANDARD,

    /**
     * 强模型档：对话总结、内容生成等质量优先任务。
     */
    PRO
}
